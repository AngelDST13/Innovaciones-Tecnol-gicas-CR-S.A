BEGIN;

-- ----------------------------------------------------------------------------
-- Extensión vectorial (base de embeddings del RAG)
-- ----------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS vector;

-- ----------------------------------------------------------------------------
-- consultas_chat: tema para el "Top 5 temas" y origen para separar datos simulados
-- ----------------------------------------------------------------------------
ALTER TABLE consultas_chat ADD COLUMN IF NOT EXISTS tema   TEXT;
ALTER TABLE consultas_chat ADD COLUMN IF NOT EXISTS origen TEXT NOT NULL DEFAULT 'real';

ALTER TABLE consultas_chat DROP CONSTRAINT IF EXISTS chk_consultas_origen;
ALTER TABLE consultas_chat ADD CONSTRAINT chk_consultas_origen CHECK (origen IN ('real', 'seed'));

CREATE INDEX IF NOT EXISTS idx_consultas_origen_fecha ON consultas_chat (origen, fecha);

-- ----------------------------------------------------------------------------
-- calendario_pagos (pregunta 9: "¿qué día cae mi próximo pago?")
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS calendario_pagos (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_pago  DATE NOT NULL UNIQUE,
    tipo        TEXT NOT NULL CHECK (tipo IN ('planilla_quincenal', 'planilla_mensual', 'aguinaldo')),
    descripcion TEXT
);

-- ----------------------------------------------------------------------------
-- evaluaciones_desempeno (pregunta 17: "¿cuándo es mi próxima evaluación?")
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS evaluaciones_desempeno (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    colaborador_id    INTEGER NOT NULL REFERENCES colaboradores (id) ON DELETE CASCADE,
    fecha_programada  DATE NOT NULL,
    estado            TEXT NOT NULL DEFAULT 'programada' CHECK (estado IN ('programada', 'completada', 'cancelada')),
    calificacion      NUMERIC(3, 1) NULL CHECK (calificacion IS NULL OR calificacion BETWEEN 0 AND 100)
);

CREATE INDEX IF NOT EXISTS idx_evaluaciones_colaborador ON evaluaciones_desempeno (colaborador_id, fecha_programada);

-- ----------------------------------------------------------------------------
-- Metadatos de Drive (sin fragmentos todavía: la dimensión del embedding se decide
-- con el modelo elegido y se añade en la migración del RAG)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS documentos_politica (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drive_file_id       TEXT NOT NULL UNIQUE,
    titulo              TEXT NOT NULL,
    version             TEXT NOT NULL,
    fecha_vigencia      DATE NULL,
    responsable         TEXT NULL,
    enlace              TEXT NULL,
    fecha_modificacion  TIMESTAMPTZ NULL,
    eliminado           BOOLEAN NOT NULL DEFAULT FALSE,
    indexado_en         TIMESTAMPTZ NULL
);

CREATE TABLE IF NOT EXISTS sync_drive_estado (
    id           INTEGER PRIMARY KEY DEFAULT 1 CHECK (id = 1),  -- una sola fila: estado de la sincronización
    page_token   TEXT NULL,                                     -- pageToken de changes.list
    ultima_sync  TIMESTAMPTZ NULL
);

INSERT INTO sync_drive_estado (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

-- ----------------------------------------------------------------------------
-- RLS en las tablas nuevas (igual que las originales; el backend usa postgres)
-- ----------------------------------------------------------------------------
ALTER TABLE calendario_pagos        ENABLE ROW LEVEL SECURITY;
ALTER TABLE evaluaciones_desempeno  ENABLE ROW LEVEL SECURITY;
ALTER TABLE documentos_politica     ENABLE ROW LEVEL SECURITY;
ALTER TABLE sync_drive_estado       ENABLE ROW LEVEL SECURITY;

COMMIT;
