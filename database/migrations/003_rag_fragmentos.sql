-- Modelo de embeddings: Xenova/multilingual-e5-small (384 dimensiones, local, sin costo por uso).
-- Qué hace:
--   - Crea fragmentos_politica: un fragmento por punto/sección/fila de calendario, con su vector.
--   - Crea un índice HNSW por coseno para la búsqueda de similitud.
--   - Activa RLS (el backend usa postgres; el agente de datos usa agente_lectura, que no tiene acceso).
-- Seguro de repetir: IF NOT EXISTS en todo.
-- ============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS fragmentos_politica (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id         INTEGER NOT NULL REFERENCES documentos_politica (id) ON DELETE CASCADE,
    codigo               TEXT NOT NULL,                 -- POL-01 … POL-10, POL-CAL
    version              TEXT NULL,
    tipo_fragmento       TEXT NOT NULL CHECK (tipo_fragmento IN ('punto', 'seccion', 'calendario')),
    seccion              INTEGER NULL,
    seccion_titulo       TEXT NULL,
    punto                TEXT NULL,                     -- p. ej. "1.1"
    orden                INTEGER NOT NULL,
    metadatos_documento  TEXT NULL,                     -- vigencia, responsable, fuente normativa
    contenido            TEXT NOT NULL,
    por_validar          BOOLEAN NOT NULL DEFAULT FALSE,
    hash_contenido       TEXT NOT NULL,                 -- detecta fragmentos sin cambios en la ingesta incremental
    embedding            VECTOR(384) NOT NULL,
    creado_en            TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_fragmentos_documento ON fragmentos_politica (documento_id, orden);
CREATE INDEX IF NOT EXISTS idx_fragmentos_codigo ON fragmentos_politica (codigo);
CREATE INDEX IF NOT EXISTS idx_fragmentos_embedding ON fragmentos_politica USING hnsw (embedding vector_cosine_ops);

ALTER TABLE fragmentos_politica ENABLE ROW LEVEL SECURITY;

COMMIT;
