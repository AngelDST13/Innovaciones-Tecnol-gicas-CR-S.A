-- ============================================================================
-- Migración 005 · Tickets de escalamiento a RRHH (NO destructiva)
-- Innovaciones Tecnológicas CR S.A · Mini Proyecto #2
--
-- Cuando el agente de políticas no encuentra la respuesta, el agente de escalamiento crea un
-- ticket para que una persona de RRHH la atienda. Seguro de repetir: IF NOT EXISTS.
-- ============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS tickets_escalamiento (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    colaborador_id  INTEGER NOT NULL REFERENCES colaboradores (id) ON DELETE CASCADE,
    pregunta        TEXT NOT NULL,
    motivo          TEXT NOT NULL CHECK (motivo IN ('sin_respuesta_en_documentos', 'solicitud_del_colaborador')),
    estado          TEXT NOT NULL DEFAULT 'abierto' CHECK (estado IN ('abierto', 'en_revision', 'cerrado')),
    creado_en       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_tickets_estado ON tickets_escalamiento (estado, creado_en);

ALTER TABLE tickets_escalamiento ENABLE ROW LEVEL SECURITY;

COMMIT;
