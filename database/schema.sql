BEGIN;

-- ----------------------------------------------------------------------------
-- Limpieza (orden inverso a las dependencias)
-- ----------------------------------------------------------------------------
DROP TABLE IF EXISTS reportes_diarios      CASCADE;
DROP TABLE IF EXISTS consultas_chat        CASCADE;
DROP TABLE IF EXISTS movimientos_personal  CASCADE;
DROP TABLE IF EXISTS incapacidades         CASCADE;
DROP TABLE IF EXISTS solicitudes           CASCADE;
DROP TABLE IF EXISTS saldos_vacaciones     CASCADE;
DROP TABLE IF EXISTS colaboradores         CASCADE;

DROP TYPE IF EXISTS rol_usuario;
DROP TYPE IF EXISTS estado_colaborador;
DROP TYPE IF EXISTS tipo_solicitud;
DROP TYPE IF EXISTS estado_solicitud;
DROP TYPE IF EXISTS tipo_incapacidad;
DROP TYPE IF EXISTS tipo_movimiento;
DROP TYPE IF EXISTS intencion_consulta;
DROP TYPE IF EXISTS agente_consulta;

-- ----------------------------------------------------------------------------
-- Tipos enumerados
-- ----------------------------------------------------------------------------
CREATE TYPE rol_usuario         AS ENUM ('colaborador', 'rrhh');
CREATE TYPE estado_colaborador  AS ENUM ('activo', 'inactivo');
CREATE TYPE tipo_solicitud      AS ENUM ('vacaciones', 'permiso', 'teletrabajo', 'licencia', 'otro');
CREATE TYPE estado_solicitud    AS ENUM ('pendiente', 'aprobada', 'rechazada');
CREATE TYPE tipo_incapacidad    AS ENUM ('enfermedad', 'maternidad', 'riesgo_laboral', 'otra');
CREATE TYPE tipo_movimiento     AS ENUM ('ingreso', 'salida', 'ascenso');
CREATE TYPE intencion_consulta  AS ENUM ('politica', 'dato_personal', 'mixta', 'restringida', 'fuera_de_alcance');
CREATE TYPE agente_consulta     AS ENUM ('orquestador', 'politicas', 'datos', 'politicas_datos', 'analista', 'ninguno');

-- ----------------------------------------------------------------------------
-- colaboradores
-- Fuente de verdad de identidad y rol.
-- ----------------------------------------------------------------------------
CREATE TABLE colaboradores (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(120)       NOT NULL,
    email         VARCHAR(160)       NOT NULL UNIQUE,
    departamento  VARCHAR(80)        NOT NULL,
    puesto        VARCHAR(120)       NOT NULL,
    fecha_ingreso DATE               NOT NULL,
    jefe_id       INTEGER            NULL REFERENCES colaboradores (id) ON DELETE SET NULL ON UPDATE CASCADE,
    rol           rol_usuario        NOT NULL DEFAULT 'colaborador',
    estado        estado_colaborador NOT NULL DEFAULT 'activo'
);

CREATE INDEX idx_colaboradores_jefe       ON colaboradores (jefe_id);
CREATE INDEX idx_colaboradores_rol_estado ON colaboradores (rol, estado);

-- ----------------------------------------------------------------------------
-- saldos_vacaciones
-- dias_disponibles es columna generada (no se escribe directamente).
-- ----------------------------------------------------------------------------
CREATE TABLE saldos_vacaciones (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    colaborador_id   INTEGER      NOT NULL REFERENCES colaboradores (id) ON DELETE CASCADE ON UPDATE CASCADE,
    periodo          VARCHAR(9)   NOT NULL,                       -- ej. '2026' o '2025-2026'
    dias_asignados   NUMERIC(5,2) NOT NULL DEFAULT 0,
    dias_tomados     NUMERIC(5,2) NOT NULL DEFAULT 0,
    dias_disponibles NUMERIC(5,2) GENERATED ALWAYS AS (dias_asignados - dias_tomados) STORED,
    CONSTRAINT uq_saldo_colaborador_periodo UNIQUE (colaborador_id, periodo),
    CONSTRAINT chk_saldo_asignados_no_negativo CHECK (dias_asignados >= 0),
    CONSTRAINT chk_saldo_tomados_no_negativo   CHECK (dias_tomados >= 0)
);

-- ----------------------------------------------------------------------------
-- solicitudes
-- aprobador_id apunta a un colaborador con rol 'rrhh' o al jefe directo.
-- ----------------------------------------------------------------------------
CREATE TABLE solicitudes (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    colaborador_id INTEGER          NOT NULL REFERENCES colaboradores (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    tipo           tipo_solicitud   NOT NULL,
    fecha_inicio   DATE             NOT NULL,
    fecha_fin      DATE             NOT NULL,
    estado         estado_solicitud NOT NULL DEFAULT 'pendiente',
    aprobador_id   INTEGER          NULL REFERENCES colaboradores (id) ON DELETE SET NULL ON UPDATE CASCADE,
    creada_en      TIMESTAMPTZ      NOT NULL DEFAULT now(),
    CONSTRAINT chk_solicitudes_fechas CHECK (fecha_fin >= fecha_inicio)
);

CREATE INDEX idx_solicitudes_colaborador  ON solicitudes (colaborador_id);
CREATE INDEX idx_solicitudes_aprobador    ON solicitudes (aprobador_id);
CREATE INDEX idx_solicitudes_estado_fecha ON solicitudes (estado, creada_en);

-- ----------------------------------------------------------------------------
-- incapacidades (CCSS)
-- ----------------------------------------------------------------------------
CREATE TABLE incapacidades (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    colaborador_id INTEGER          NOT NULL REFERENCES colaboradores (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    tipo           tipo_incapacidad NOT NULL,
    fecha_inicio   DATE             NOT NULL,
    dias           SMALLINT         NOT NULL,
    entidad        VARCHAR(80)      NOT NULL DEFAULT 'CCSS',
    CONSTRAINT chk_incapacidades_dias CHECK (dias > 0)
);

CREATE INDEX idx_incapacidades_colaborador ON incapacidades (colaborador_id);
CREATE INDEX idx_incapacidades_fecha       ON incapacidades (fecha_inicio);

-- ----------------------------------------------------------------------------
-- movimientos_personal (altas, bajas y promociones)
-- ----------------------------------------------------------------------------
CREATE TABLE movimientos_personal (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    colaborador_id INTEGER         NOT NULL REFERENCES colaboradores (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    tipo           tipo_movimiento NOT NULL,
    fecha          DATE            NOT NULL,
    motivo         VARCHAR(255)    NULL
);

CREATE INDEX idx_movimientos_colaborador ON movimientos_personal (colaborador_id);
CREATE INDEX idx_movimientos_tipo_fecha  ON movimientos_personal (tipo, fecha);

-- ----------------------------------------------------------------------------
-- consultas_chat (auditoría y métricas del chatbot)
-- colaborador_id NULL = consulta sin identificar.
-- ----------------------------------------------------------------------------
CREATE TABLE consultas_chat (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    colaborador_id     INTEGER           NULL REFERENCES colaboradores (id) ON DELETE SET NULL ON UPDATE CASCADE,
    pregunta           TEXT              NOT NULL,
    intencion          intencion_consulta NULL,
    agente             agente_consulta   NOT NULL DEFAULT 'orquestador',
    documentos_citados JSONB             NULL,
    resuelta           BOOLEAN           NOT NULL DEFAULT FALSE,
    escalada           BOOLEAN           NOT NULL DEFAULT FALSE,
    latencia_ms        INTEGER           NULL CHECK (latencia_ms IS NULL OR latencia_ms >= 0),
    fecha              TIMESTAMPTZ       NOT NULL DEFAULT now()
);

CREATE INDEX idx_consultas_colaborador_fecha ON consultas_chat (colaborador_id, fecha);
CREATE INDEX idx_consultas_fecha             ON consultas_chat (fecha);
CREATE INDEX idx_consultas_intencion         ON consultas_chat (intencion);

-- ----------------------------------------------------------------------------
-- reportes_diarios (salida del Agente Analista)
-- ----------------------------------------------------------------------------
CREATE TABLE reportes_diarios (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha         DATE        NOT NULL UNIQUE,
    datos_json    JSONB       NOT NULL,
    resumen_texto TEXT        NULL,
    generado_por  VARCHAR(80) NOT NULL DEFAULT 'agente_analista'
);

-- ----------------------------------------------------------------------------
-- Seguridad en Supabase
-- Activa RLS en todas las tablas. Sin políticas, el rol anon/authenticated de la
-- Data API de Supabase no puede leer ni escribir. El backend se conecta con el
-- rol postgres, que no está sujeto a RLS (verificar en tu proyecto).
-- ----------------------------------------------------------------------------
ALTER TABLE colaboradores         ENABLE ROW LEVEL SECURITY;
ALTER TABLE saldos_vacaciones     ENABLE ROW LEVEL SECURITY;
ALTER TABLE solicitudes           ENABLE ROW LEVEL SECURITY;
ALTER TABLE incapacidades         ENABLE ROW LEVEL SECURITY;
ALTER TABLE movimientos_personal  ENABLE ROW LEVEL SECURITY;
ALTER TABLE consultas_chat        ENABLE ROW LEVEL SECURITY;
ALTER TABLE reportes_diarios      ENABLE ROW LEVEL SECURITY;

